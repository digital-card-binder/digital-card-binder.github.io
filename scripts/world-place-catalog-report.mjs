const sets = data.map((set) => ({
  setCode: set.code,
  setName: set.displayName || set.title || '',
  cards: set.cards || []
}));

for (const [region, queries] of Object.entries(regionQueries)) {
  const matches = [];
  for (const set of sets) {
    for (const card of set.cards) {
      const name = String(card.name || '').trim();
      if (!name || !queries.some((q) => name.includes(q))) continue;
      matches.push({
        setCode: set.setCode,
        setName: set.setName,
        cardCode: card.code,
        name,
        image: card.image || '',
        source: card.source || ''
      });
    }
  }
  console.log(`===${region} ${matches.length}===`);
  for (const row of matches) {
    console.log([region, row.setCode, row.setName, row.cardCode, row.name, row.image, row.source].join('\t'));
  }
}
